-- Per-developer, per-CWE mastery (Plan A). Runs on PostgreSQL and on H2 in PostgreSQL mode.
CREATE TABLE dev_skill (
    dev_hash       VARCHAR(64)              NOT NULL,
    cwe_id         VARCHAR(16)              NOT NULL,
    mastery        DOUBLE PRECISION         NOT NULL CHECK (mastery >= 0 AND mastery <= 1),
    events_count   INTEGER                  NOT NULL,
    last_event_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (dev_hash, cwe_id)
);

-- Audit trail of every mastery update, for re-explaining and for evaluation.
CREATE TABLE skill_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dev_hash        VARCHAR(64)              NOT NULL,
    cwe_id          VARCHAR(16)              NOT NULL,
    event_type      VARCHAR(16)              NOT NULL,
    mastery_before  DOUBLE PRECISION         NOT NULL,
    mastery_after   DOUBLE PRECISION         NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_skill_event_dev_cwe ON skill_event (dev_hash, cwe_id, created_at);
