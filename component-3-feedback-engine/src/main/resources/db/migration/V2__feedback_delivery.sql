-- Plan B: every decision is stored so it can be re-explained exactly and analysed later.
CREATE TABLE feedback_decision (
    id                  VARCHAR(64)              PRIMARY KEY,
    event_id            VARCHAR(128)             NOT NULL,
    dev_hash            VARCHAR(64)              NOT NULL,
    cwe_id              VARCHAR(16)              NOT NULL,
    severity            VARCHAR(16)              NOT NULL,
    file_ref            VARCHAR(512)             NOT NULL,
    score               DOUBLE PRECISION         NOT NULL,
    base_level          INTEGER                  NOT NULL,
    level               INTEGER                  NOT NULL,
    channel             VARCHAR(16)              NOT NULL,
    interruptive        BOOLEAN                  NOT NULL,
    mastery             DOUBLE PRECISION         NOT NULL,
    breakdown_json      VARCHAR(1000)            NOT NULL,
    reasons_json        VARCHAR(2000)            NOT NULL,
    adjustments_json    VARCHAR(2000)            NOT NULL,
    delivery_notes_json VARCHAR(2000)            NOT NULL,
    narrative           VARCHAR(2000)            NOT NULL,
    policy_version      VARCHAR(32)              NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_decision_dev_time ON feedback_decision (dev_hash, created_at);
CREATE INDEX idx_decision_dev_cwe_file ON feedback_decision (dev_hash, cwe_id, file_ref, created_at);

-- What the IDE did with the notice: shown, expanded, dismissed (quick dismissal = annoyance signal).
CREATE TABLE notice_log (
    decision_id    VARCHAR(64)              PRIMARY KEY REFERENCES feedback_decision (id),
    shown_at       TIMESTAMP WITH TIME ZONE,
    expanded       BOOLEAN                  NOT NULL,
    dismissed_at   TIMESTAMP WITH TIME ZONE,
    quick_dismiss  BOOLEAN                  NOT NULL
);

-- What the developer did about the finding.
CREATE TABLE feedback_outcome (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    decision_id         VARCHAR(64)              NOT NULL UNIQUE REFERENCES feedback_decision (id),
    dev_hash            VARCHAR(64)              NOT NULL,
    cwe_id              VARCHAR(16)              NOT NULL,
    outcome             VARCHAR(16)              NOT NULL,
    time_to_outcome_sec BIGINT                   NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_outcome_dev_cwe ON feedback_outcome (dev_hash, cwe_id, created_at);

-- "Helpful" / "Not helpful" / "Too much" votes from the Why panel.
CREATE TABLE feedback_vote (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    decision_id  VARCHAR(64)              NOT NULL REFERENCES feedback_decision (id),
    dev_hash     VARCHAR(64)              NOT NULL,
    vote         VARCHAR(16)              NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_vote_dev_time ON feedback_vote (dev_hash, created_at);
